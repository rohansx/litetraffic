"""A standalone bash repro for a failing run: the cause (an author's repro.sh, a curl per failing kit sample, or an honest
timeline) and the effect (the failed final observation re-read and checked). LiteTraffic is not needed to run it."""

from __future__ import annotations

import hashlib
import json
import re
import shlex
from pathlib import Path
from urllib.parse import quote

from litetraffic import __version__
from litetraffic.auth import secret_env_names

AUTHOR_REPRO = "repro.sh"
MAX_SAMPLES = 3  # per assertion, the same cap the kit script records (MAX_FAILURE_SAMPLES)
STATUS_ASSERTIONS = ("cross_tenant_read_blocked", "cross_tenant_write_blocked", "unauthenticated_rejected")
UNAUTHENTICATED = "unauthenticated"
PLACEHOLDER = re.compile(r"\{([A-Za-z_][A-Za-z0-9_]*)\}")
REPRO_JOURNEY = "repro"  # stands in for the journey key in `{journey}` placeholders

HELPERS = r"""LT_VIOLATED=0
LT_CHECKED=0
LT_WORK="$(mktemp -d)"
trap 'rm -rf "$LT_WORK"' EXIT
"""


CONTROL = re.compile(r"[\x00-\x1f\x7f-\x9f\u2028\u2029]+")
ENV_NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def _flat(text: object) -> str:
    """One line: newlines and other control characters become single spaces."""
    return CONTROL.sub(" ", str(text))


def _dq(text: object) -> str:
    """`text` on one line, escaped for the inside of a bash double-quoted string."""
    return re.sub(r'(["\\$`])', r"\\\1", _flat(text))


def _comment(text: object) -> str:
    """`text` safe after a `#`: a newline cannot end the comment and start a command."""
    return _flat(text)


def _env(name: object) -> str:
    """An environment variable name that is safe inside ${...}; anything else cannot be referenced."""
    if not isinstance(name, str) or not ENV_NAME.match(name):
        from litetraffic.issue import IssueError

        raise IssueError(f"refusing to write a repro that reads the environment variable {_flat(name)!r}: not a valid name")
    return name


def _markers_env(identity: str) -> str:
    return "LT_MARKERS_" + re.sub(r"[^A-Z0-9]+", "_", identity.upper()).strip("_")


def _header(evidence, env_names: list[str]) -> list[str]:
    files = evidence.lock.get("files") if isinstance(evidence.lock.get("files"), dict) else {}
    script = evidence.manifest_data.get("script")
    lines = [
        "#!/usr/bin/env bash",
        "set -euo pipefail",
        _comment(f"# Standalone repro for LiteTraffic run {evidence.run_id} (scenario {evidence.run.get('scenario')})."),
        _comment(f"# scenario sha256 {evidence.run.get('scenario_sha256')}; seed {evidence.run.get('seed')}"),
    ]
    if script in files:
        lines.append(_comment(f"# {script} sha256 {files[script]}"))
    lines += [
        f"# generated by LiteTraffic {__version__}; LiteTraffic is not needed to run it.",
        "# Credentials come only from the environment variables checked below; none are written here.",
        "# Exit 1 means the failure reproduced, 0 means it did not, 2 means the script could not check.",
        '[ -n "${TARGET:-}" ] || { echo "repro.sh: set TARGET to the app base URL" >&2; exit 2; }',
        *(f'[ -n "${{{_env(name)}:-}}" ] || {{ echo "repro.sh: set {name} (a credential this repro reads from the environment)" >&2; exit 2; }}'
          for name in env_names),
        "for tool in curl python3; do",
        '  command -v "$tool" >/dev/null || { echo "repro.sh needs $tool" >&2; exit 2; }',
        "done",
        "# A step that fails before the check means the script could not check: exit 2, never 1.",
        "set -E",
        "trap 'echo \"repro.sh: a step failed at line $LINENO before the check could finish\" >&2; exit 2' ERR",
        'TARGET="${TARGET%/}"',
        HELPERS.rstrip("\n"),
        "",
    ]
    return lines


def author_repro(scenario_dir: Path | None) -> tuple[str, str] | None:
    """(text, sha256) of the scenario author's repro.sh, by convention DIR/repro.sh, or None."""
    if scenario_dir is None:
        return None
    path = Path(scenario_dir) / AUTHOR_REPRO
    if not path.is_file():
        return None
    data = path.read_bytes()
    return data.decode("utf-8", errors="replace"), hashlib.sha256(data).hexdigest()


def _author_section(text: str, digest: str) -> list[str]:
    return [
        "# === cause ===",
        f"# --- provided by the scenario author (sha256 {digest}) ---",
        text.rstrip("\n"),
        "# --- end of the scenario author's repro ---",
        "",
    ]


def _timeline_section(evidence, kit_run: bool) -> list[str]:
    from litetraffic.issue import traffic

    files = evidence.lock.get("files") if isinstance(evidence.lock.get("files"), dict) else {}
    script = str(evidence.manifest_data.get("script") or "journeys.js")
    digest = files.get(script, "unknown")
    lines = ["# === cause ===", "# What the run sent, from metrics.jsonl (paths are relative to $TARGET; ids became {id}):"]
    for entry in traffic(evidence):
        statuses = ", ".join(f"{status} x{count}" for status, count in entry["statuses"].items())
        lines.append(_comment(f"#   {entry['operation']}: {entry['method']} {entry['path']} — {entry['requests']} requests ({statuses})"))
    if not evidence.requests:
        lines.append("#   (no requests were recorded)")
    lines.append(_comment(
        f"# LiteTraffic does not record request bodies, so this script cannot replay the cause. {script} (sha256 {digest}) "
        "describes the requests; pass --scenario with a repro.sh to include one."
    ))
    if kit_run:
        lines.append("# This is a tenant-isolation kit run: pass --scenario DIR (the generated kit scenario) to get a curl per failing sample.")
    return [*lines, ""]


# Mirrors observation._pointer/_matches, so the script judges the response as the run did. Exit 0: every expectation
# holds; 1: one does not on the final attempt; 3: one does not yet (retry); 2: the response is not JSON.
EFFECT_CHECK = r'''import json, sys
EXPECTED = json.loads(__EXPECTED__)
body_path, final = sys.argv[1], sys.argv[2] == "1"
try:
    with open(body_path, encoding="utf-8") as body:
        document = json.load(body)
except ValueError:
    print("the observation response is not JSON; cannot check it")
    sys.exit(2)
MISSING = object()


def pointer(doc, path):
    for part in path[1:].split("/") if path else []:
        key = part.replace("~1", "/").replace("~0", "~")
        if isinstance(doc, dict) and key in doc:
            doc = doc[key]
        elif isinstance(doc, list) and key.isdecimal() and int(key) < len(doc):
            doc = doc[int(key)]
        else:
            return MISSING
    return doc


def equal(a, b):
    if isinstance(a, bool) or isinstance(b, bool):
        return type(a) is type(b) and a == b
    if isinstance(a, list) and isinstance(b, list):
        return len(a) == len(b) and all(map(equal, a, b))
    if isinstance(a, dict) and isinstance(b, dict):
        return a.keys() == b.keys() and all(equal(a[k], b[k]) for k in a)
    return a == b


def number(value):
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def holds(op, operand, actual):
    if op == "exists":
        return (actual is not MISSING) == operand
    if actual is MISSING:
        return False
    if op == "eq":
        return equal(actual, operand)
    if op == "len":
        return isinstance(actual, (list, str, dict)) and len(actual) == operand
    if not (number(actual) and number(operand)):
        return False
    return actual >= operand if op == "gte" else actual <= operand


SYMBOLS = {"eq": "=", "gte": ">=", "lte": "<=", "len": "length =", "exists": "exists ="}
results, lines = [], []
for path, matcher in EXPECTED.items():
    (op, operand), = matcher.items()
    actual = pointer(document, path)
    shown = "missing" if actual is MISSING else json.dumps(actual)[:200]
    results.append(holds(op, operand, actual))
    lines.append("EXPECTED %s %s %s ACTUAL %s %s" % (path, SYMBOLS.get(op, op), json.dumps(operand), shown, "OK" if results[-1] else "VIOLATED"))
if all(results) or final:
    print("\n".join(lines))
if all(results):
    sys.exit(0)
sys.exit(1 if final else 3)
'''


def _recorded_matchers(evidence) -> dict[str, dict]:
    """assertion -> {pointer: matcher} as the run resolved them, from observation.json (an object or a list)."""
    entries = evidence.observation if isinstance(evidence.observation, list) else [evidence.observation]
    found = {}
    for entry in entries:
        if isinstance(entry, dict) and isinstance(entry.get("checks"), dict):
            matchers = {pointer: check.get("matcher") for pointer, check in entry["checks"].items() if isinstance(check, dict)}
            if all(isinstance(matcher, dict) and len(matcher) == 1 for matcher in matchers.values()):
                found[entry.get("assertion")] = matchers
    return found


def _matchers(evidence, observation) -> dict[str, dict]:
    from litetraffic.observation_config import as_matcher, resolve_expected

    recorded = _recorded_matchers(evidence).get(observation.assertion)
    if recorded:
        return recorded
    variables = {"planned_journeys": int(evidence.result.get("planned_journeys") or 0), "seed": int(evidence.run.get("seed") or 0)}
    try:
        expected = resolve_expected(observation.expected, variables)
    except ValueError:
        expected = observation.expected
    return {pointer: as_matcher(value) for pointer, value in expected.items()}


def _observation_headers(observation) -> list[str]:
    headers = ["-H 'Accept: application/json'"]
    if observation.bearer_token_env:
        headers.append(f'-H "Authorization: Bearer ${{{_env(observation.bearer_token_env)}}}"')
    for name, env in sorted(observation.headers_env.items()):
        headers.append(f'-H "{_dq(name)}: ${{{_env(env)}}}"')
    return headers


def _observation_base(observation) -> str:
    if observation.origin_env:
        return f"${{{_env(observation.origin_env)}%/}}"
    if observation.origin:
        return _dq(observation.origin.rstrip("/"))
    return "$TARGET"


def _effect_section(evidence, observation) -> list[str]:
    until = observation.until
    deadline = int(-(-until.deadline_seconds // 1)) if until else 0
    interval = f"{until.interval_seconds:g}" if until else "1"
    label = _dq(observation.assertion)
    url = f'"{_observation_base(observation)}{_dq(observation.path)}"'
    check = EFFECT_CHECK.replace("__EXPECTED__", json.dumps(json.dumps(_matchers(evidence, observation), sort_keys=True)))
    return [
        _comment(f"# === effect: {observation.assertion} ==="),
        _comment(f"# Re-read GET {observation.path} until it holds or {deadline}s pass (the run's deadline; override with REPRO_DEADLINE_SECONDS)."),
        f'lt_deadline=$(( $(date +%s) + ${{REPRO_DEADLINE_SECONDS:-{deadline}}} ))',
        "while :; do",
        "  lt_final=0",
        '  [ "$(date +%s)" -lt "$lt_deadline" ] || lt_final=1',
        f"  lt_status=$(curl -sS -o \"$LT_WORK/effect\" -w '%{{http_code}}' {' '.join(_observation_headers(observation))} {url}) \\",
        f'    || {{ echo "{label}: the observation request failed" >&2; exit 2; }}',
        '  case "$lt_status" in',
        "    2??) ;;",
        f'    *) echo "{label}: the observation answered HTTP $lt_status; cannot check it" >&2; exit 2 ;;',
        "  esac",
        "  lt_rc=0",
        '  python3 - "$LT_WORK/effect" "$lt_final" <<\'PY\' || lt_rc=$?',
        check.rstrip("\n"),
        "PY",
        '  [ "$lt_rc" -eq 3 ] || break',
        f"  sleep {interval}",
        "done",
        "LT_CHECKED=1",
        'case "$lt_rc" in',
        "  0) ;;",
        f'  1) LT_VIOLATED=1; echo "{label}: VIOLATED" ;;',
        "  *) exit 2 ;;",
        "esac",
        "",
    ]


def failed_observations(evidence) -> list:
    from litetraffic.issue import failing

    if evidence.manifest is None:
        return []
    ids = {row["id"] for row in failing(evidence)}
    return [observation for observation in evidence.manifest.observations if observation.assertion in ids]


def _verdict() -> list[str]:
    return [
        "# === verdict ===",
        'if [ "$LT_VIOLATED" -eq 1 ]; then echo "REPRODUCED: the failure LiteTraffic saw happened again"; exit 1; fi',
        'if [ "$LT_CHECKED" -eq 0 ]; then echo "nothing to check: this repro has no effect check for these failures"; exit 2; fi',
        'echo "not reproduced this time (failures under load can depend on timing; rerun a few times)"',
        "exit 0",
        "",
    ]


def synthesize(evidence, scenario_dir: Path | None, scrubber) -> str:
    """The repro script, scrubbed; credentials are referenced as ${ENV} and never inlined."""
    from litetraffic.issue import _kit_run, scenario_kit

    observations = failed_observations(evidence)
    kit_run = bool(_kit_run(evidence.manifest_data))
    authored = author_repro(scenario_dir)
    kit = None
    if scenario_dir is not None and authored is None and kit_run:
        kit = scenario_kit({str(evidence.manifest_data.get("script")): Path(scenario_dir) / str(evidence.manifest_data.get("script"))}, evidence)
    needed = set(secret_env_names(evidence.manifest)) if evidence.manifest else set()
    needed |= {o.origin_env for o in observations if o.origin_env}
    body: list[str] = []
    if authored is not None:
        body += _author_section(*authored)
    elif kit is not None:
        section, envs = _kit_section(evidence, kit)
        body += section
        needed |= envs
    else:
        body += _timeline_section(evidence, kit_run)
    for observation in observations:
        body += _effect_section(evidence, observation)
    lines = [*_header(evidence, sorted(needed)), *body, *_verdict()]
    return scrubber.text("\n".join(lines))


KIT_HELPERS = r"""lt_has_marker() {  # body file, markers (one per line)
  local marker
  while IFS= read -r marker; do
    [ -n "$marker" ] && grep -qF -- "$marker" "$1" && return 0
  done <<< "$2"
  return 1
}
lt_check() {  # label, status, allowed statuses (empty: any), the owner's markers (one per line; empty: not checked)
  local bad=0
  if [ -n "$3" ] && [[ " $3 " != *" $2 "* ]]; then echo "$1: expected one of $3, got $2"; bad=1; fi
  if [ -n "$4" ] && lt_has_marker "$LT_WORK/body" "$4"; then echo "$1: the response carries the owner's marker"; bad=1; fi
  LT_CHECKED=1
  if [ "$bad" -eq 1 ]; then echo "$1: VIOLATED"; LT_VIOLATED=1; else echo "$1: OK (HTTP $2)"; fi
}"""


def _fill(template, ref: dict, encode):
    if isinstance(template, str):
        return PLACEHOLDER.sub(lambda m: encode(str(ref[m.group(1)])) if m.group(1) in ref else m.group(0), template)
    if isinstance(template, list):
        return [_fill(item, ref, encode) for item in template]
    if isinstance(template, dict):
        return {key: _fill(item, ref, encode) for key, item in template.items()}
    return template


def _kit_samples(evidence, kit: dict) -> list[tuple[str, dict]]:
    from litetraffic.issue import failing

    found = []
    for row in failing(evidence):
        if row["id"] not in (kit.get("assertions") or []):
            continue
        samples = [
            sample
            for failure in row.get("failures") or [] if isinstance(failure, dict) and isinstance(failure.get("actual"), dict)
            for sample in failure["actual"].get("samples") or [] if isinstance(sample, dict)
        ]
        found += [(row["id"], sample) for sample in samples[:MAX_SAMPLES]]
    return found


def _owner(kit: dict, ref: object) -> dict | None:
    return next((i for i in kit.get("identities") or [] if isinstance(i, dict) and ref in (i.get("resources") or [])), None)


def _kit_request(assertion: str, sample: dict, kit: dict, identities: dict) -> tuple[list[str], set[str]]:
    """The curl and its check for one failing sample, with the attacker's credentials as env references."""
    identity = identities.get(sample.get("identity")) or {"name": UNAUTHENTICATED, "headers": {}, "token_env": None}
    method, template = str(sample.get("method") or "GET").upper(), str(sample.get("path") or "/")
    endpoint = next((e for e in kit.get("endpoints") or [] if e.get("method", "").upper() == method and e.get("path") == template), {})
    ref = {**(sample.get("id") if isinstance(sample.get("id"), dict) else {}), "journey": REPRO_JOURNEY}
    path = _fill(template, ref, lambda text: quote(text, safe=""))
    args, envs = ["-X", shlex.quote(method)], set()
    for name, value in sorted((identity.get("headers") or {}).items()):
        args += ["-H", shlex.quote(f"{name}: {value}")]
    if identity.get("token_env"):
        envs.add(_env(identity["token_env"]))
        args += ["-H", f'"Authorization: Bearer ${{{_env(identity["token_env"])}}}"']
    attacking = assertion in ("cross_tenant_write_blocked", "victim_unchanged")
    payload = endpoint.get("attack_body") if attacking else endpoint.get("body")
    if endpoint.get("kind") == "write" and payload is not None:
        args += ["-H", "'Content-Type: application/json'", "--data-binary", shlex.quote(json.dumps(_fill(payload, ref, str)))]
    who = identity.get("name")
    label = _dq(f"{assertion} ({who} {method} {path})")
    marked = sample.get("markers") if isinstance(sample.get("markers"), dict) else {}
    victim = marked.get("identity") or (_owner(kit, sample.get("id")) or {}).get("name")
    lines = [
        _comment(f"# {assertion}: {who} sent {method} {template} for {json.dumps(sample.get('id'), sort_keys=True)}; "
                 f"the run saw HTTP {sample.get('status')}" + (f" carrying {victim}'s marker(s) {marked.get('indexes')}" if marked else "")),
        f"lt_status=$(curl -sS -o \"$LT_WORK/body\" -w '%{{http_code}}' {' '.join(args)} \"$TARGET{_dq(path)}\") \\",
        f'  || {{ echo "{label}: the request failed" >&2; exit 2; }}',
    ]
    if assertion == "victim_unchanged":
        lines.append(f'echo "{label}: sent (HTTP $lt_status); read the resource as its owner to see whether it changed"')
        return [*lines, ""], envs
    allowed = " ".join(str(status) for status in kit.get("rejected") or []) if assertion in STATUS_ASSERTIONS else ""
    markers = f'"${{{_markers_env(victim)}:-}}"' if victim else '""'
    lines.append(f'lt_check "{label}" "$lt_status" "{allowed}" {markers}')
    return [*lines, ""], envs


def _kit_section(evidence, kit: dict) -> tuple[list[str], set[str]]:
    identities = {i.get("name"): i for i in kit.get("identities") or [] if isinstance(i, dict)}
    samples = _kit_samples(evidence, kit)
    names = sorted({_markers_env(name) for name in identities if name})
    lines = [
        "# === cause: one request per failing sample (at most %d per assertion) ===" % MAX_SAMPLES,
        f"# Marker checks read each owner's markers, one per line, from {', '.join(names) or 'LT_MARKERS_<IDENTITY>'};",
        "# unset, only the status is checked. Marker values are never written here.",
        KIT_HELPERS,
        "",
    ]
    envs: set[str] = set()
    for assertion, sample in samples:
        section, needed = _kit_request(assertion, sample, kit, identities)
        lines += section
        envs |= needed
    if not samples:
        lines += ["# The failing assertions recorded no per-request samples to replay.", ""]
    return lines, envs
